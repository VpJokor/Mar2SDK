/**
 * 从一次已加载的 AdMob 广告中读取虚拟探针的执行证据。
 *
 * 虚拟探针是一个只返回“可识别主动 no-fill”的自定义中介事件。AdMob 会
 * 把这次尝试的结果放进本次广告的 [ResponseInfo]，读取器再把这些响应项
 * 转换成保守的代理价格结果。预期处理顺序如下：
 *
 * 1. 找到本次加载请求唯一的胜出适配器响应。
 * 2. 按 AdMob 返回的原始瀑布顺序遍历适配器响应。
 * 3. 使用 [ProbeConfig] 在请求开始时冻结的探针清单匹配响应。
 * 4. 检查响应是否包含探针适配器约定的错误域和错误码；必要时在有限深度
 *    的 `cause` 链中查找，不能只依赖错误文本。
 * 5. 只统计胜出来源之前、且确认返回主动 no-fill 的探针。代理价取这些探针
 *    eCPM 的最小值，因为它表示胜出来源排序价格的保守上界，而不是精确价格。
 *
 * 读取必须采用失败闭合策略：胜出项缺失或不唯一、实例重复或未知、排序无法
 * 验证、配置不匹配、错误链无法识别时，都只能返回未知结果。仅凭标签、零延迟
 * 或相同的错误消息，不能证明探针确实被执行。
 *
 * 本类不发起广告请求、不读取 AdMob 私有字段，也不上报收益。现有
 * [AdmobReflectProbe] 是对已加载广告对象做展示前价格读取的独立工具，其结果
 * 不能替代本代理信号。实现时也不能用全局可变探针状态，否则并发请求可能串用
 * 彼此的响应证据。
